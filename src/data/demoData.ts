/**
 * Resolves category resolution for both parent categories and nested subcategories.
 */
export interface ResolvedCategoryContext {
  category?: Category;
  subcategory?: Subcategory;
  parentCategory?: Category;
  isSubcategory: boolean;
  articles: Article[];
  popularArticles: Article[];
  recentArticles: Article[];
}

export function resolveCategoryBySlug(slug: string): ResolvedCategoryContext | null {
  if (slug === 'all') {
    const allArticles = [...DEMO_ARTICLES];
    return {
      category: {
        id: 'cat-all',
        slug: 'all',
        name: 'All Disciplines & Categories',
        description: 'Comprehensive overview of all 13 core knowledge domains and specialist sub-disciplines.',
        iconName: 'Compass',
        articleCount: allArticles.length,
      },
      isSubcategory: false,
      articles: allArticles,
      popularArticles: [...allArticles].sort((a, b) => b.views - a.views).slice(0, 4),
      recentArticles: [...allArticles].sort((a, b) => b.lastUpdated.localeCompare(a.lastUpdated)).slice(0, 4),
    };
  }

  // 1. Try finding as a main category
  const mainCat = DEMO_CATEGORIES.find((c) => c.slug === slug);
  if (mainCat) {
    const categoryArticles = DEMO_ARTICLES.filter((a) => a.categorySlug === slug);
    return {
      category: mainCat,
      isSubcategory: false,
      articles: categoryArticles,
      popularArticles: categoryArticles.filter((a) => a.popular).slice(0, 3),
      recentArticles: [...categoryArticles].sort((a, b) => b.lastUpdated.localeCompare(a.lastUpdated)).slice(0, 3),
    };
  }

  // 2. Try finding as a subcategory
  for (const parent of DEMO_CATEGORIES) {
    if (parent.subcategories) {
      const sub = parent.subcategories.find((s) => s.slug === slug);
      if (sub) {
        // Find articles matching this subcategory or parent
        const subArticles = DEMO_ARTICLES.filter((a) => {
          if (a.categorySlug === parent.slug) {
            // Check subcategory match or tag match
            if (a.subCategory && a.subCategory.toLowerCase().includes(sub.name.toLowerCase().split(' ')[0])) {
              return true;
            }
            if (sub.featuredArticleSlug === a.slug) {
              return true;
            }
            if (a.tags.some((t) => t.toLowerCase().includes(sub.name.toLowerCase().split(' ')[0]))) {
              return true;
            }
          }
          return false;
        });

        return {
          category: undefined,
          subcategory: sub,
          parentCategory: parent,
          isSubcategory: true,
          articles: subArticles,
          popularArticles: subArticles.filter((a) => a.popular).slice(0, 3),
          recentArticles: [...subArticles].sort((a, b) => b.lastUpdated.localeCompare(a.lastUpdated)).slice(0, 3),
        };
      }
    }
  }

  return null;
}

